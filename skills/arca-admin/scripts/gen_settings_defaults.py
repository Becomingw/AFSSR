#!/usr/bin/env python3
"""Generate references/product/settings-defaults.md from the code's system-config defaults.

The key list and default values come from `admin_system_config_default_value` in
crates/aether-admin/src/system.rs, so they cannot drift. The meaning of each key is written by hand
in references/product/settings-glossary.md; `--check` fails when

  * settings-defaults.md is stale, or
  * a key in the code has no `### <key>` entry in the glossary (and is not listed under
    "## 待补" there), or
  * the glossary describes a key that no longer exists in the code.

    python3 skills/arca-admin/scripts/gen_settings_defaults.py          # rewrite
    python3 skills/arca-admin/scripts/gen_settings_defaults.py --check  # verify (exit 1 on drift)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'crates/aether-admin/src/system.rs'
PRODUCT = pathlib.Path(__file__).resolve().parents[1] / 'references/product'
OUT = PRODUCT / 'settings-defaults.md'
GLOSSARY = PRODUCT / 'settings-glossary.md'

CONSTANTS = {'REQUEST_RECORD_LEVEL_KEY': 'request_record_level'}


def default_function_body():
    text = SOURCE.read_text()
    start = text.index('pub fn admin_system_config_default_value')
    end = text.index('pub fn build_admin_system_configs_payload')
    return text[start:end]


def render_default(expr):
    expr = ' '.join(expr.split())
    if expr == 'serde_json::Value::Null':
        return 'null'
    m = re.fullmatch(r'json!\((.*)\)', expr)
    if m:
        inner = m.group(1).strip()
        return re.sub(r'\s+', ' ', inner)
    return f'(computed: `{expr}`)'


def parse():
    body = default_function_body()
    arms = []
    # Arms look like `<"key" | CONSTANT> => Some(<expr>),` and can span lines (sensitive_headers),
    # so find each start and walk to the matching parenthesis.
    pos = 0
    arm = re.compile(r'\n\s*("([^"]+)"|([A-Z][A-Z_]+))\s*=>\s*Some\(')
    while True:
        m = arm.search(body, pos)
        if not m:
            break
        key = m.group(2) or CONSTANTS[m.group(3)]
        i, depth = m.end(), 1
        while depth:
            depth += {'(': 1, ')': -1}.get(body[i], 0)
            i += 1
        arms.append((key, render_default(body[m.end():i - 1])))
        pos = i
    return arms


def group_of(key):
    if key.startswith('backup_s3_'):
        return 'S3 备份'
    if key.startswith('smtp_'):
        return '邮件 (SMTP)'
    if key.startswith('module.'):
        return '功能模块（通知、推送、PII 脱敏）'
    if key.startswith('turnstile_'):
        return '登录防护 (Turnstile)'
    if 'retention' in key or 'cleanup' in key or key in ('enable_auto_cleanup', 'enable_db_maintenance'):
        return '数据保留与清理'
    return '其他'


def render(arms):
    lines = ['# 系统设置默认值', '',
             '<!-- Generated by scripts/gen_settings_defaults.py from crates/aether-admin/src/system.rs. Do not edit by hand. -->', '',
             '这里只有**代码里的默认值**（未设置时生效的值）。每一项的含义、影响和风险见 [settings-glossary.md](settings-glossary.md)。',
             '实际当前值用 `arca_system_config`（单项）或 `arca_system_configs`（全部，敏感值已脱敏）读取。', '']
    groups = {}
    for key, default in arms:
        groups.setdefault(group_of(key), []).append((key, default))
    for name in sorted(groups, key=lambda g: (g == '其他', g)):
        lines += [f'## {name}', '', '| 键 | 默认值 |', '| --- | --- |']
        for key, default in groups[name]:
            shown = default.replace('|', '\\|')
            if len(shown) > 120:
                shown = shown[:117] + '...'
            lines.append(f'| `{key}` | `{shown}` |' if not shown.startswith('(computed') else f'| `{key}` | {shown} |')
        lines.append('')
    lines.append(f'共 {len(arms)} 项。')
    return '\n'.join(lines) + '\n'


def glossary_keys():
    if not GLOSSARY.exists():
        return set(), set()
    text = GLOSSARY.read_text()
    documented = set(re.findall(r'^###\s+`([^`]+)`', text, re.M))
    pending = set()
    m = re.search(r'^## 待补\s*$(.*?)(?=^## |\Z)', text, re.M | re.S)
    if m:
        pending = set(re.findall(r'`([^`]+)`', m.group(1)))
    return documented, pending


def extra_keys():
    """Keys documented under "## 不在默认值表中的键": real settings the code reads that have no default entry."""
    if not GLOSSARY.exists():
        return set()
    m = re.search(r'^## 不在默认值表中的键\s*$(.*?)(?=^## |\Z)', GLOSSARY.read_text(), re.M | re.S)
    return set(re.findall(r'^###\s+`([^`]+)`', m.group(1), re.M)) if m else set()


def main():
    arms = parse()
    if len(arms) < 50:
        raise SystemExit(f'parser found only {len(arms)} defaults; the source layout probably changed')
    text = render(arms)
    if '--check' not in sys.argv:
        OUT.write_text(text)
        print(f'wrote {OUT.relative_to(ROOT)} ({len(arms)} keys)')
        return 0
    problems = []
    if not OUT.exists() or OUT.read_text() != text:
        problems.append('settings-defaults.md is stale; run the script without --check')
    keys = {k for k, _ in arms}
    documented, pending = glossary_keys()
    missing = sorted(keys - documented - pending)
    if missing:
        problems.append('keys without a glossary entry (add "### `key`" or list under "## 待补"): ' + ', '.join(missing))
    unknown = sorted((documented | pending) - keys - extra_keys())
    if unknown:
        problems.append('glossary mentions keys that do not exist in code: ' + ', '.join(unknown))
    for problem in problems:
        print('FAIL', problem)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())

#!/usr/bin/env python3
"""Regenerate references/tool-map.md from the authoritative MCP operation catalog.

    python3 skills/arca-admin/scripts/gen_tool_map.py          # rewrite the file
    python3 skills/arca-admin/scripts/gen_tool_map.py --check  # exit 1 if it is stale
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
CATALOG = ROOT / 'apps/aether-gateway/src/api/mcp/catalog.rs'
OUT = pathlib.Path(__file__).resolve().parents[1] / 'references/tool-map.md'

OP = re.compile(r'op!\("(\w+)",\s*"(\w+)",\s*"([^"]+)",\s*(\w+),\s*"((?:[^"\\]|\\.)*)"\)')
GROUPS = [
    ('Feedback, diagnostics and offline checks', ('feedback_', 'request_diagnostics', 'leaderboard_', 'compatibility_', 'benefits_preview')),
    ('Users, groups, keys and benefits', ('users_', 'groups_', 'keys_', 'benefits_')),
    ('Providers, models and upstream credentials', ('providers_', 'provider_models_', 'model_test', 'models_', 'endpoints_', 'upstream_keys_')),
    ('Health, pools and adaptive concurrency', ('health_', 'rpm_', 'pool_', 'adaptive_')),
    ('Routing and proxy/tunnel nodes', ('routing_', 'proxy_', 'ops_')),
    ('Tasks', ('tasks_', 'video_')),
    ('Usage, statistics and monitoring', ('usage_', 'stats_', 'monitor_')),
    ('System, modules, announcements and LDAP', ('system_', 'modules_', 'announcements_', 'ldap_')),
]
APPROVAL = {'Read': 'none', 'Change': 'preview + confirm', 'External': 'preview + confirm + **human OK** (uses stored credentials / contacts a target, may cost money)', 'Destructive': 'preview + confirm + **human OK**'}


def first_sentence(text):
    text = text.replace('\\"', '"')
    sentence = re.split(r'(?<=[.!?])\s', text, maxsplit=1)[0]
    if len(sentence) <= 150:
        return sentence
    return sentence[:150].rsplit(' ', 1)[0] + ' ...'


def render():
    ops = OP.findall(CATALOG.read_text())
    seen, lines = set(), [
        '# Arca MCP tool map', '',
        '<!-- Generated by scripts/gen_tool_map.py from api/mcp/catalog.rs. Do not edit by hand. -->', '',
        'Every tool is prefixed `afssr_` (a kept wire-level name). `path` takes the ids in `{braces}`;',
        '`query` takes filters; writes also take `body`, `dry_run` (default true) and `confirmation`.',
        'Impact decides the approval you need: **Read** is free; **Change** needs preview + confirmation;',
        '**External** and **Destructive** additionally need an explicit human go-ahead for that specific action.', '',
        f'{len(ops)} operations, plus `afssr_identity`. `tools/list` only shows what your role and key scopes permit.', '']
    for title, prefixes in GROUPS:
        rows = [o for o in ops if o[0] not in seen and o[0].startswith(prefixes)]
        if not rows:
            continue
        seen.update(o[0] for o in rows)
        lines += [f'## {title}', '', '| Tool | Method and path | Impact | Purpose |', '| --- | --- | --- | --- |']
        for name, method, path, impact, desc in rows:
            lines.append(f'| `afssr_{name}` | `{method} {path}` | {impact} | {first_sentence(desc)} |')
        lines.append('')
    rest = [o for o in ops if o[0] not in seen]
    if rest:
        raise SystemExit('ungrouped operations, extend GROUPS: ' + ', '.join(o[0] for o in rest))
    lines += ['## Approval by impact', '', '| Impact | Needs |', '| --- | --- |'] + [f'| {k} | {v} |' for k, v in APPROVAL.items()] + ['']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f'wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)')
